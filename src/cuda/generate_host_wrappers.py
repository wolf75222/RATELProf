"""Generate host-library interposers from Clang's view of the SDK headers."""

import argparse
import json
from pathlib import Path
import subprocess
import sys


DOMAINS = ("Mpi", "Cublas", "Nccl", "OmpRoutine")
UNSUPPORTED_ATTRIBUTES = {
    "AliasAttr",
    "AsmLabelAttr",
    "ErrorAttr",
    "IFuncAttr",
    "UnavailableAttr",
    "WeakRefAttr",
}


def ast_nodes(text):
    """Read the separate JSON objects printed by a filtered Clang AST dump."""
    decoder = json.JSONDecoder()
    end = 0
    while True:
        while end < len(text) and text[end].isspace():
            end += 1
        if end >= len(text):
            return
        item, end = decoder.raw_decode(text, end)
        yield item


def functions(node):
    if node.get("kind") == "FunctionDecl":
        yield node
        return
    for child in node.get("inner", ()):
        yield from functions(child)


def read_declarations(options):
    source = "#define OMPI_SKIP_MPICXX 1\n#define MPICH_SKIP_MPICXX 1\n"
    source += "".join(f"#include {json.dumps(header)}\n" for header in options.header)
    clang = [options.clang, "-x", "c++", "-std=c++17", "-fsyntax-only",
             "-Wno-deprecated-declarations", "-Xclang", "-ast-dump=json"]
    for directory in options.include:
        clang.extend(("-I", directory))
    declarations = {}
    excluded = set()
    overloaded = set()
    prefixes = tuple(options.prefix)
    for prefix in prefixes:
        result = subprocess.run(
            [*clang, "-Xclang", "-ast-dump-filter", "-Xclang", prefix, "-"],
            input=source, text=True, capture_output=True,
        )
        if result.returncode:
            raise ValueError(f"Clang cannot read the {options.domain} SDK headers:\n{result.stderr.strip()}")
        for tree in ast_nodes(result.stdout):
            for function in functions(tree):
                name = function.get("name", "")
                if not name.startswith(prefixes):
                    continue
                mangled_name = function.get("mangledName")
                if mangled_name not in (name, f"_{name}"):
                    if mangled_name:
                        overloaded.add(name)
                    continue
                children = function.get("inner", ())
                forbidden = any(child.get("kind") in UNSUPPORTED_ATTRIBUTES or
                                child.get("kind") == "CompoundStmt" for child in children)
                if function.get("variadic") or function.get("inline") or function.get("isImplicit") or \
                        function.get("storageClass") == "static" or forbidden:
                    excluded.add(name)
                    continue
                parameters = [(child.get("name") or f"arg{index}", child["type"]["qualType"])
                              for index, child in enumerate(child for child in children
                                                            if child.get("kind") == "ParmVarDecl")]
                declarations[name] = (parameters, function["type"]["qualType"])

    return {name: (parameters, sdk_type if name in overloaded else None)
            for name, (parameters, sdk_type) in declarations.items() if name not in excluded}


PREAMBLE = """// Generated by generate_host_wrappers.py from the SDK headers.
#include <cstddef>
#include <tuple>
#include <type_traits>
#include <utility>

namespace ratelprof_generated_host {

// Derive the ABI types from the actual C declaration. This avoids inserting
// parameter names into array and function-pointer declarators.
template<class> struct Signature;

template<class Result, class... Arguments>
struct Signature<Result (*)(Arguments...)> {
    using Return = Result;
    template<std::size_t Index>
    using Argument = std::tuple_element_t<Index, std::tuple<Arguments...>>;
    static constexpr bool is_noexcept = false;
};

template<class Result, class... Arguments>
struct Signature<Result (*)(Arguments...) noexcept> : Signature<Result (*)(Arguments...)> {
    static constexpr bool is_noexcept = true;
};

} // namespace ratelprof_generated_host
"""


def generate_wrapper(domain, name, parameters, overloaded_type):
    signature = f"RatelprofSignature_{name}"
    pointer = f"decltype(&({name}))"
    if overloaded_type:
        # Some headers add a C++ overload next to the exported C declaration.
        # Select the exact C signature before asking the compiler for its ABI.
        pointer = f"decltype(static_cast<std::add_pointer_t<{overloaded_type}>>(&({name})))"
    arg_type = [f"{signature}::Argument<{index}>" for index in range(len(parameters))]
    arg_name = [f"arg{index}" for index in range(len(parameters))]
    declaration = ", ".join(f"{type_name} {variable}" for type_name, variable in zip(arg_type, arg_name))
    forwarding = ", ".join(f"std::forward<{type_name}>({variable})"
                           for type_name, variable in zip(arg_type, arg_name))
    fields = ",\n".join(f"            {{{json.dumps(param)}, {json.dumps(sdk_type)}, trace_argument_value({variable})}}"
                         for (param, sdk_type), variable in zip(parameters, arg_name))
    arguments = "TraceArguments{}"
    if fields:
        arguments = f"TraceArguments{{\n{fields}\n        }}"

    return f"""
using {signature} = ratelprof_generated_host::Signature<{pointer}>;
extern "C" auto ({name})({declaration}) noexcept({signature}::is_noexcept) -> {signature}::Return
{{
    static const auto original = resolve<{pointer}>("{name}");
    return traced({domain}, "{name}", __builtin_return_address(0),
                  [&] {{ return original({forwarding}); }},
                  [&] {{ return {arguments}; }});
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", required=True)
    parser.add_argument("--domain", choices=DOMAINS, required=True)
    parser.add_argument("--prefix", action="append", required=True)
    parser.add_argument("--header", action="append", required=True)
    parser.add_argument("--include", action="append", default=[])
    parser.add_argument("--output", type=Path, required=True)
    options = parser.parse_args()
    try:
        declarations = read_declarations(options)
        if not declarations:
            raise ValueError(f"no eligible C functions in the {options.domain} SDK headers")
        text = PREAMBLE + "".join(generate_wrapper(options.domain, name, *declaration)
                                  for name, declaration in sorted(declarations.items()))
        options.output.write_text(text, encoding="utf-8")
    except (OSError, ValueError) as error:
        print(f"generate_host_wrappers: {error}", file=sys.stderr)
        return 1
    print(f"Generated {len(declarations)} {options.domain} host wrappers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
